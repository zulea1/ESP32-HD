static const size_t HD_DTC_DATABASE_SIZE = sizeof(HD_DTC_DATABASE) / sizeof(HD_DTC_DATABASE[0]);

/**
 * @brief Looks up a HD DTC description from the PROGMEM database.
 * Matches 5-character base codes like "P0107", "B2206", "C1021", "U0141".
 */
inline const char* lookupHDDtcDescription(const char* baseCode) {
    if (baseCode == nullptr || strlen(baseCode) < 4) {
        return "HD Diagnostic Trouble Code";
    }

    char cleanCode[8] = {0};
    uint8_t cleanIndex = 0;
    for (size_t charIndex = 0; charIndex < strlen(baseCode) && cleanIndex < 5; charIndex++) {
        if (baseCode[charIndex] != '-' && baseCode[charIndex] != ' ') {
            cleanCode[cleanIndex++] = toupper((unsigned char)baseCode[charIndex]);
        }
    }
    cleanCode[cleanIndex] = '\0';

    for (size_t entryIndex = 0; entryIndex < HD_DTC_DATABASE_SIZE; entryIndex++) {
        char databaseCode[8];
        memcpy_P(databaseCode, HD_DTC_DATABASE[entryIndex].code, sizeof(databaseCode));
        if (strcmp(cleanCode, databaseCode) == 0) {
            return HD_DTC_DATABASE[entryIndex].desc;
        }
    }

    // Category fallbacks if exact code not matched
    if (cleanCode[0] == 'P') return "HD Powertrain / Engine Fault";
    if (cleanCode[0] == 'B') return "HD Body / Lighting / Switch Fault";
    if (cleanCode[0] == 'C') return "HD ABS / Chassis Brake Fault";
    if (cleanCode[0] == 'U') return "HD CAN Bus Network Communication Loss";
    return "HD Diagnostic Trouble Code";
}
